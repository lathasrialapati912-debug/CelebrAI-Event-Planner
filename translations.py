def translate(key: str, language_name: str, **values: Any) -> str:
    """Translate a UI key, falling back to its English copy when unavailable."""
    locale = LANGUAGES.get(language_name, "en")
    text = TRANSLATIONS.get(locale, {}).get(key, ENGLISH.get(key, key))
    return text.format(**values) if values else text


def t(key: str, **values: Any) -> str:
    """Translate a UI key using the current session language."""
    language_name = "English"
    try:
        import streamlit as st

        language_name = st.session_state.get("celebrai_language", "English")
    except (ImportError, RuntimeError):
        pass

    return translate(key, language_name, **values)


def missing_translation_keys() -> dict[str, list[str]]:
    """Return keys absent from a locale, for tests and translation maintenance."""
    english_keys = set(ENGLISH)
    return {
        locale: sorted(english_keys.difference(translations))
        for locale, translations in TRANSLATIONS.items()
        if english_keys.difference(translations)
    }


def translation_key_diagnostics() -> dict[str, dict[str, list[str]]]:
    """Report translation keys missing from or unused by each locale."""
    english_keys = set(ENGLISH)
    diagnostics = {}
    for locale, translations in TRANSLATIONS.items():
        missing = sorted(english_keys.difference(translations))
        unused = sorted(set(translations).difference(english_keys))
        if missing or unused:
            diagnostics[locale] = {"missing": missing, "unused": unused}
    return diagnostics
